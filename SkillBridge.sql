-- PART 7: QUERY BANK LEVEL-1
-- BASIC SQL QUERIES
-- =====================================================================================================
-- DISPLAY ALL STUDENTS
SELECT*FROM STUDENTS;

-- DISPLAY ALL SKILLS
SELECT*FROM SKILLS;

-- DISPLAY  SPECIFIC STUDENT DETAILS
SELECT STUDENT_ID,STUDENT_NAME FROM STUDENTS;

-- FIND THE STUDENTS USING WHERE 
SELECT*FROM STUDENTS WHERE STUDENT_ID=1;

-- SORT  STUDENTS USING  ORDER BY
SELECT*FROM STUDENTS ORDER BY STUDENT_NAME ASC;

-- COUNT TOTAL STUDENTS
SELECT COUNT(*) AS TOTAL_STUDENTS FROM STUDENTS;

-- SEARCH OPPORTUNITIES USING LIKE
SELECT*FROM OPPORTUNITIES WHERE OPPORTUNITY_TITLE LIKE '%INTERNSHIP%';
-- =============================================================================================
-- PART 8: QUERY BANK LEVEL 2
-- =============================================================================================
-- COUNT AND GROUP BY
SELECT STATUS, COUNT(*) AS TOTAL_APPLICATIONS FROM APPLICATIONS GROUP BY STATUS; 

-- MAXIMUM STIPEND
SELECT MAX(STIPEND) AS MAXIMUM_STIPEND  FROM OPPORTUNITIES;

-- FIND AVERAGE STIPEND
SELECT AVG(STIPEND) AS AVERAGE_STIPEND FROM OPPORTUNITIES;

-- FIND SKILLS HAVING MORE THAN ONE STUDENT 
SELECT  SKILL_ID,COUNT(*) AS TOTAL_STUDENTS FROM STUDENT_SKILLS GROUP BY SKILL_ID HAVING COUNT(*)>1;

-- =============================================================================================
-- PART 9 : QUERY BANK LEVEL 3
-- =============================================================================================
-- INNER JOIN - STUDENTS AND SKILLS
SELECT S.STUDENT_NAME ,SK.SKILL_NAME,SS.PROFICIENCY FROM STUDENTS S INNER JOIN STUDENT_SKILLS SS ON  S.STUDENT_ID=SS.STUDENT_ID INNER JOIN SKILLS SK  ON SS.SKILL_ID=SK.SKILL_ID;

-- INNER JOIN - COMPANIES AND OPPORTUNITIES
SELECT C.COMPANY_NAME,O.OPPORTUNITY_TITLE,O.STIPEND FROM COMPANIES C INNER JOIN OPPORTUNITIES O ON C.COMPANY_ID=O.COMPANY_ID;

-- LEFT JOIN - STUDENTS AND APPLICATIONS
SELECT S.STUDENT_NAME,A.APPLICATION_ID,A.STATUS FROM STUDENTS S LEFT JOIN APPLICATIONS A ON S.STUDENT_ID=A.STUDENT_ID;

