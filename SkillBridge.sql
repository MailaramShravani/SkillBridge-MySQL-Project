-- Create Application Status History Table

CREATE TABLE IF NOT EXISTS application_status_history (
    history_id INT AUTO_INCREMENT PRIMARY KEY,
    application_id INT,
    old_status VARCHAR(30),
    new_status VARCHAR(30),
    changed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Create Application Status Update Trigger

DROP TRIGGER IF EXISTS trg_application_status_update;

DELIMITER //

CREATE TRIGGER trg_application_status_update
AFTER UPDATE ON applications
FOR EACH ROW
BEGIN
    IF NOT (OLD.STATUS <=> NEW.STATUS) THEN
        INSERT INTO application_status_history
        (application_id, old_status, new_status)
        VALUES
        (NEW.APPLICATION_ID, OLD.STATUS, NEW.STATUS);
    END IF;
END //

DELIMITER ;

