CREATE VIEW STUDENT_SKILLS_VIEW AS SELECT
 S.STUDENT_ID,
S.STUDENT_NAME,
SK.SKILL_NAME,
SS.PROFICIENCY FROM STUDENTS AS S JOIN STUDENT_SKILLS AS  SS ON S.STUDENT_ID = SS.STUDENT_ID JOIN  SKILLS AS SK ON SS.SKILL_ID=SK.SKILL_ID;

CREATE VIEW  COMPANY_OPPORTUNITIES_VIEW AS SELECT 
C.COMPANY_ID,
C.COMPANY_NAME,
O.OPPORTUNITY_ID,
O.OPPORTUNITY_TITLE,
O.OPPORTUNITY_TYPE,
O.STIPEND,
O.DEADLINE  FROM COMPANIES C JOIN OPPORTUNITIES O ON C.COMPANY_ID = O.COMPANY_ID;
SELECT*FROM COMPANY_OPPORTUNITIES_VIEW;
